import type { RunManifest } from './types.js';

export interface GitHubPublishOptions {
  token: string;
  repository: string;
  prNumber: number;
  apiUrl?: string;
  fetchImpl?: typeof fetch;
}

export interface GitHubPublishResult {
  summaryAction: 'created' | 'updated';
  inlineCreated: number;
  inlineSkipped: number;
  errors: string[];
}

const SUMMARY_MARKER = '<!-- review-tool:summary -->';

function markerFor(fingerprint: string): string {
  return `<!-- review-tool:${fingerprint} -->`;
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function buildSummaryBody(manifest: RunManifest): string {
  const reported = manifest.findings.filter((finding) => finding.status === 'reported');
  const needsHuman = manifest.findings.filter((finding) => finding.status === 'needs_human');
  const blockers = reported.filter((finding) => finding.severity === 'blocker').length;
  const rows = [...reported, ...needsHuman]
    .slice(0, 20)
    .map(
      (finding) =>
        `| ${finding.severity} | ${finding.category} | ${escapeCell(`${finding.file}:${finding.line}`)} | ${escapeCell(finding.claim)} |`,
    );
  return [
    SUMMARY_MARKER,
    `## AI review: ${manifest.status} (exit ${manifest.exitCode})`,
    '',
    `- Run: \`${manifest.runId}\``,
    `- Mode / tier: \`${manifest.mode}\` / \`${manifest.tier}\``,
    `- Findings: ${reported.length} reported (${blockers} blocker), ${needsHuman.length} needs human`,
    `- Checks: ${manifest.checks.length} configured`,
    `- Head: \`${manifest.git.headSha}\``,
    '',
    rows.length
      ? ['| Severity | Category | Location | Claim |', '|---|---|---|---|', ...rows].join('\n')
      : 'No published findings.',
    '',
    '_Generated by review-tool. Details are in the run artifacts._',
  ].join('\n');
}

function buildInlineBody(finding: RunManifest['findings'][number]): string {
  return [
    markerFor(finding.fingerprint),
    `**${finding.severity} · ${finding.category}**`,
    '',
    finding.claim,
    '',
    `**Evidence:** ${finding.evidence}`,
    finding.suggestion ? `\n**Suggestion:** ${finding.suggestion}` : '',
    '',
    `Verification: \`${finding.verification}\``,
  ].join('\n');
}

class GitHubClient {
  constructor(
    private readonly token: string,
    private readonly apiUrl: string,
    private readonly fetchImpl: typeof fetch,
  ) {}

  private async request(method: string, path: string, body?: unknown): Promise<unknown> {
    const response = await this.fetchImpl(`${this.apiUrl}${path}`, {
      method,
      headers: {
        authorization: `Bearer ${this.token}`,
        accept: 'application/vnd.github+json',
        'content-type': 'application/json',
        'user-agent': 'review-tool',
        'x-github-api-version': '2022-11-28',
      },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await response.text();
    if (!response.ok) {
      throw new Error(`GitHub API ${method} ${path} failed: ${response.status} ${text.slice(0, 500)}`);
    }
    return text ? JSON.parse(text) : null;
  }

  async listIssueComments(repository: string, prNumber: number): Promise<Array<{ id: number; body: string }>> {
    return (await this.request(
      'GET',
      `/repos/${repository}/issues/${prNumber}/comments?per_page=100`,
    )) as Array<{ id: number; body: string }>;
  }

  async updateIssueComment(repository: string, commentId: number, body: string): Promise<void> {
    await this.request('PATCH', `/repos/${repository}/issues/comments/${commentId}`, { body });
  }

  async createIssueComment(repository: string, prNumber: number, body: string): Promise<void> {
    await this.request('POST', `/repos/${repository}/issues/${prNumber}/comments`, { body });
  }

  async listReviewComments(repository: string, prNumber: number): Promise<Array<{ id: number; body: string }>> {
    return (await this.request(
      'GET',
      `/repos/${repository}/pulls/${prNumber}/comments?per_page=100`,
    )) as Array<{ id: number; body: string }>;
  }

  async createReviewComment(
    repository: string,
    prNumber: number,
    body: string,
    finding: RunManifest['findings'][number],
    headSha: string,
  ): Promise<void> {
    await this.request('POST', `/repos/${repository}/pulls/${prNumber}/comments`, {
      body,
      commit_id: headSha,
      path: finding.file,
      line: finding.endLine,
      ...(finding.endLine > finding.line ? { start_line: finding.line, start_side: 'RIGHT' } : {}),
      side: 'RIGHT',
    });
  }
}

export async function publishReview(
  manifest: RunManifest,
  options: GitHubPublishOptions,
): Promise<GitHubPublishResult> {
  const client = new GitHubClient(
    options.token,
    (options.apiUrl ?? 'https://api.github.com').replace(/\/+$/, ''),
    options.fetchImpl ?? fetch,
  );
  const errors: string[] = [];

  const summaryBody = buildSummaryBody(manifest);
  let summaryAction: 'created' | 'updated' = 'created';
  try {
    const comments = await client.listIssueComments(options.repository, options.prNumber);
    const existing = comments.find((comment) => comment.body.includes(SUMMARY_MARKER));
    if (existing) {
      await client.updateIssueComment(options.repository, existing.id, summaryBody);
      summaryAction = 'updated';
    } else {
      await client.createIssueComment(options.repository, options.prNumber, summaryBody);
    }
  } catch (error) {
    errors.push(error instanceof Error ? error.message : String(error));
  }

  let inlineCreated = 0;
  let inlineSkipped = 0;
  let existingComments: Array<{ id: number; body: string }> = [];
  try {
    existingComments = await client.listReviewComments(options.repository, options.prNumber);
  } catch (error) {
    errors.push(error instanceof Error ? error.message : String(error));
  }

  const toPublish = manifest.findings.filter(
    (finding) =>
      finding.status === 'reported' &&
      (finding.severity === 'blocker' || finding.severity === 'important'),
  );
  for (const finding of toPublish) {
    const marker = markerFor(finding.fingerprint);
    if (existingComments.some((comment) => comment.body.includes(marker))) {
      inlineSkipped += 1;
      continue;
    }
    try {
      await client.createReviewComment(
        options.repository,
        options.prNumber,
        buildInlineBody(finding),
        finding,
        manifest.git.headSha,
      );
      inlineCreated += 1;
    } catch (error) {
      errors.push(error instanceof Error ? error.message : String(error));
    }
  }

  return { summaryAction, inlineCreated, inlineSkipped, errors };
}

export function githubOptionsFromEnv(
  env: NodeJS.ProcessEnv = process.env,
): GitHubPublishOptions {
  const token = env.GITHUB_TOKEN;
  const repository = env.GITHUB_REPOSITORY;
  const prNumber = Number(env.PR_NUMBER ?? env.GITHUB_PR_NUMBER ?? 0);
  if (!token) throw new Error('GITHUB_TOKEN is required to publish a review.');
  if (!repository) throw new Error('GITHUB_REPOSITORY is required to publish a review.');
  if (!Number.isInteger(prNumber) || prNumber <= 0) {
    throw new Error('PR_NUMBER (or GITHUB_PR_NUMBER) is required to publish a review.');
  }
  return {
    token,
    repository,
    prNumber,
    apiUrl: env.GITHUB_API_URL,
  };
}
